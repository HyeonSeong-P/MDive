#!/usr/bin/env python3
"""Export the approved SVG mark to Android vector/adaptive/legacy launcher resources."""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'app/src/main/res'
ANDROID = 'http://schemas.android.com/apk/res/android'
ET.register_namespace('android', ANDROID)


def attr(**values):
    return {f'{{{ANDROID}}}{key}': str(value) for key, value in values.items()}


def xml(element):
    ET.indent(element)
    return '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate_launcher_icons.py. Do not edit. -->\n' + ET.tostring(element, encoding='unicode') + '\n'


def generate():
    palette = json.loads((ROOT / 'design-system/tokens.json').read_text())['themes']['deepsea']['colors']['dark']
    mark = ET.parse(ROOT / 'design-system/brand/mdive-mark.svg').getroot()
    if mark.get('viewBox') != '0 0 1254 1254':
        raise ValueError('Recheck launcher sizing before changing the approved mark canvas')
    if any(path.get('fill') not in ['#DCE8EA', '#80CAD4'] for path in mark):
        raise ValueError('Map each brand color to a palette role before exporting')
    # Center the approved 1254-unit outline in the 108dp layer's safe zone (about 60dp wide).
    def vector(monochrome=False, legacy=None):
        viewport = 108 if legacy is None else 72
        root = ET.Element('vector', attr(width=f'{108 if legacy is None else 48}dp', height=f'{108 if legacy is None else 48}dp', viewportWidth=viewport, viewportHeight=viewport))
        if legacy is not None:
            background = 'M0,0H72V72H0Z' if legacy == 'square' else 'M36,0A36,36 0,1 1,36,72A36,36 0,1 1,36,0Z'
            ET.SubElement(root, 'path', attr(fillColor=palette['background'], pathData=background))
        shift = 0 if legacy is None else -18
        group = ET.SubElement(root, 'group', attr(scaleX='0.068', scaleY='0.068', translateX=9.97 + shift, translateY=10.48 + shift))
        for path in mark:
            translation = re.fullmatch(r'translate\(([-\d.]+),([-\d.]+)\)', path.get('transform', ''))
            if not translation:
                raise ValueError('Only traced path translations are supported')
            child = ET.SubElement(group, 'group', attr(translateX=translation[1], translateY=translation[2]))
            fill = '#FFFFFFFF' if monochrome else palette['onBackground'] if path.get('fill') == '#DCE8EA' else palette['primary']
            ET.SubElement(child, 'path', attr(fillColor=fill, fillType='evenOdd', pathData=path.get('d')))
        return xml(root)

    adaptive = ET.Element('adaptive-icon')
    ET.SubElement(adaptive, 'background', attr(drawable='@color/ic_launcher_background'))
    ET.SubElement(adaptive, 'foreground', attr(drawable='@drawable/ic_launcher_foreground'))
    ET.SubElement(adaptive, 'monochrome', attr(drawable='@drawable/ic_launcher_monochrome'))
    colors = ET.Element('resources')
    ET.SubElement(colors, 'color', {'name': 'ic_launcher_background'}).text = palette['background']
    results = {
        RES / 'drawable/ic_launcher_foreground.xml': vector(),
        RES / 'drawable/ic_launcher_monochrome.xml': vector(monochrome=True),
        RES / 'drawable/ic_launcher_legacy.xml': vector(legacy='square'),
        RES / 'drawable/ic_launcher_legacy_round.xml': vector(legacy='round'),
        RES / 'values/launcher_colors.xml': xml(colors),
    }
    # The same approved geometry, cropped to the mark rather than the launcher safe-area canvas.
    brand = ET.Element('vector', attr(width='48dp', height='36dp', viewportWidth=900, viewportHeight=680))
    for path in mark:
        translation = re.fullmatch(r'translate\(([-\d.]+),([-\d.]+)\)', path.get('transform', ''))
        child = ET.SubElement(brand, 'group', attr(translateX=float(translation[1]) - 198, translateY=float(translation[2]) - 300))
        fill = palette['onBackground'] if path.get('fill') == '#DCE8EA' else palette['primary']
        ET.SubElement(child, 'path', attr(fillColor=fill, fillType='evenOdd', pathData=path.get('d')))
    results[ROOT / 'designsystem/src/main/res/drawable/mdive_brand_mark.xml'] = xml(brand)
    for name in ['ic_launcher', 'ic_launcher_round']:
        results[RES / f'mipmap-anydpi-v26/{name}.xml'] = xml(adaptive)
        target = '@drawable/ic_launcher_legacy' + ('_round' if name.endswith('round') else '')
        results[RES / f'mipmap-anydpi/{name}.xml'] = xml(ET.Element('inset', attr(drawable=target, inset='0dp')))
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Stale launcher resources:\n' + '\n'.join(stale) + '\n')
    print('Launcher resources are current.' if args.check else 'Generated launcher resources.')


if __name__ == '__main__':
    main()
