#!/usr/bin/env python3
"""Generate checked-in design outputs, or fail when they drift (--check). Stdlib only."""
import argparse
import html
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / 'designsystem/src/main/java/com/parka/mdive/designsystem/generated'


def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def generate():
    tokens = json.loads((ROOT / 'design-system/tokens.json').read_text())
    catalog = json.loads((ROOT / 'design-system/catalog.json').read_text())
    icons = json.loads((ROOT / 'design-system/icons.json').read_text())
    entries = catalog['entries']
    ids = [entry['id'] for entry in entries]
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate catalog ID')
    themes = tokens['themes']
    roles = set(themes['deepsea']['colors']['light'])
    for theme in themes.values():
        for mode in ['light', 'dark']:
            palette = theme['colors'][mode]
            if set(palette) != roles:
                raise ValueError('Theme color roles differ')
            for color in palette.values():
                if len(color) != 7 or color[0] != '#':
                    raise ValueError(f'Expected #RRGGBB: {color}')
                int(color[1:], 16)
    header = '// Generated by tools/generate_design_system.py. Do not edit.\npackage com.parka.mdive.designsystem.generated\n\n'
    kotlin = header + 'import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.TextUnit\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n\ninternal data class TypographyToken(val familyRole: String, val fontSize: TextUnit, val lineHeight: TextUnit, val weight: Int)\n\ninternal object DesignTokens {\n'
    for mode in ['light', 'dark']:
        kotlin += f'    val {mode.title()}Themes = mapOf(\n'
        for theme_id, theme in themes.items():
            pairs = ',\n'.join(f'            {quote(key)} to Color(0xFF{value[1:]})' for key, value in theme['colors'][mode].items())
            kotlin += f'        {quote(theme_id)} to mapOf(\n{pairs},\n        ),\n'
        kotlin += '    )\n'
        kotlin += f'    val {mode.title()} = {mode.title()}Themes.getValue("deepsea")\n'
    names = ', '.join(f'{quote(key)} to {quote(theme["name"])}' for key, theme in themes.items())
    kotlin += f'    val ThemeNames = mapOf({names})\n'
    for source, name, unit in [('spacing', 'Spacing', '.dp'), ('sizes', 'Sizes', '.dp'), ('fontSizes', 'FontSizes', '.sp'), ('fontRoles', 'FontRoles', ''), ('lineHeights', 'LineHeights', 'f'), ('radii', 'Radii', '.dp'), ('opacities', 'Opacities', 'f')]:
        pairs = ',\n'.join(f'        {quote(key)} to {quote(value) if isinstance(value, str) else str(value) + unit}' for key, value in tokens[source].items())
        kotlin += f'    val {name} = mapOf(\n{pairs},\n    )\n'
    kotlin += '    val Typography = mapOf(\n'
    for name, role in tokens['typography'].items():
        size = tokens['fontSizes'][role['size']]
        leading = round(size * tokens['lineHeights'][role['leading']], 4)
        family = tokens['fontRoles'].get(role['family'])
        if role['weight'] not in {'Pretendard': {400, 600}, 'JetBrains Mono': {400}}.get(family, set()):
            raise ValueError(f'Unbundled font family/weight: {name}')
        kotlin += f'        {quote(name)} to TypographyToken({quote(role["family"])}, {size}.sp, {leading}.sp, {role["weight"]}),\n'
    kotlin += '    )\n}\n'
    def kotlin_list(items):
        return 'listOf(' + ', '.join(map(quote, items)) + ')'
    fields = ['anatomy', 'variants', 'behavior', 'accessibility', 'usage']
    items = ',\n'.join('    CatalogEntry(' + quote(entry['id']) + ', ' + quote(entry['title']) + ', ' + kotlin_list(entry['states']) + ', category = ' + quote(entry['category']) + ', purpose = ' + quote(entry['purpose']) + ', ' + ', '.join(key + ' = ' + kotlin_list(entry[key]) for key in fields) + ')' for entry in entries)
    manifest = header + f'object CatalogThemes {{ val names = mapOf({names}) }}\n\n' + 'data class CatalogEntry(val id: String, val title: String, val states: List<String>, val category: String = "components", val purpose: String = "", ' + ', '.join('val ' + key + ': List<String> = emptyList()' for key in fields) + ')\n\nval catalogEntries = listOf(\n' + items + ',\n)\n'
    samples = header + 'object CatalogSamples {\n'
    for key, value in catalog['samples'].items():
        if isinstance(value, str):
            samples += f'    const val {key} = {quote(value)}\n'
        else:
            rows = ', '.join('listOf(' + ', '.join(map(quote, row)) + ')' for row in value)
            samples += f'    val {key} = listOf({rows})\n'
    samples += '}\n'
    icon_pairs = ',\n'.join(f'        {quote(key)} to {quote(path)}' for key, path in icons['paths'].items())
    icon_kotlin = header + f'object CatalogIcons {{\n    const val viewport = {icons["viewport"]}f\n    const val strokeWidth = {icons["strokeWidth"]}f\n    val paths = mapOf(\n{icon_pairs},\n    )\n}}\n'
    css = '/* Generated. Do not edit. */\n'
    for theme_id, theme in themes.items():
        for mode in ['light', 'dark']:
            css += f'[data-palette="{theme_id}"][data-theme="{mode}"] {{\n'
            css += ''.join(f'  --{key}: {value};\n' for key, value in theme['colors'][mode].items()) + '}\n'
    css += ':root {\n' + ''.join(f'  --space-{k}: {v}px;\n' for k, v in tokens['spacing'].items())
    css += ''.join(f'  --font-{k}: {v}px;\n' for k, v in tokens['fontSizes'].items())
    css += ''.join(f'  --family-{k}: "{v}";\n' for k, v in tokens['fontRoles'].items()) + '}\n'
    css += ':root {\n' + ''.join(f'  --leading-{k}: {v};\n' for k, v in tokens['lineHeights'].items())
    css += ''.join(f'  --radius-{k}: {v}px;\n' for k, v in tokens['radii'].items()) + '}\n'
    css += ':root {\n' + ''.join(f'  --size-{k}: {v}px;\n' for k, v in tokens['sizes'].items()) + '}\n'
    css += f':root {{ --icon-stroke: {icons["strokeWidth"]}; }}\n'
    css += ':root {\n' + ''.join(f'  --opacity-{k}: {v};\n' for k, v in tokens['opacities'].items()) + '}\n'
    for name, role in tokens['typography'].items():
        css += f'.type-{name} {{ font-family: var(--family-{role["family"]}); font-size: var(--font-{role["size"]}); line-height: var(--leading-{role["leading"]}); font-weight: {role["weight"]}; }}\n'
    # HTML and Compose share entries, states and fixtures; platform renderers stay handwritten.
    e = html.escape
    sample = catalog['samples']
    ET.register_namespace('', 'http://www.w3.org/2000/svg')
    brand = ET.parse(ROOT / 'design-system/brand/mdive-mark.svg').getroot()
    brand.set('viewBox', '198 300 900 680')
    brand.set('width', '96')
    brand.set('height', '72')
    brand_svg = ET.tostring(brand, encoding='unicode')
    def icon(name):
        return f'<svg class="icon" viewBox="0 0 {icons["viewport"]} {icons["viewport"]}" aria-hidden="true"><path d="{e(icons["paths"][name])}"/></svg>'

    def button(label, variant='', leading=None, disabled=False):
        disabled_attr = ' disabled' if disabled else ''
        return f'<button type="button" class="button {variant}"{disabled_attr}>{icon(leading) if leading else ""}{e(label)}</button>'

    def document_rows(rows):
        return ''.join(f'<div class="document-row">{icon("file")}<div><strong>{e(row[0])}</strong><small>{e(row[1])}</small></div>{icon("chevron")}</div>' for row in rows)

    def topbar(state):
        title = sample['longFilename'] if state == 'longTitle' else sample['filename'] if state == 'back' else 'MDive'
        nav = f'<button type="button" class="icon-button" aria-label="뒤로">{icon("back")}</button>' if state != 'default' else ''
        actions = f'<button type="button" class="icon-button" aria-label="검색">{icon("search")}</button><button type="button" class="icon-button" aria-label="즐겨찾기">{icon("star")}</button>' if state in ['actions','longTitle'] else ''
        return f'<div class="topbar">{nav}<strong title="{e(title)}">{e(title)}</strong>{actions}</div>'

    table = '<table>' + ''.join('<tr>' + ''.join(f'<td>{e(cell)}</td>' for cell in row) + '</tr>' for row in sample['table']) + '</table>'
    swatches = ''.join(f'<span class="swatch" style="background:var(--{key})">{key}</span>' for key in themes['deepsea']['colors']['light'])

    def search_bar(empty):
        query, result = ('', '—') if empty == 'idle' else ('없는 단어', '0/0') if empty else ('함수', '1/3')
        disabled = ' disabled' if empty else ''
        bar = f'<div class="search"><button type="button" class="icon-button" aria-label="검색 닫기">{icon("back")}</button><input aria-label="검색어 정적 예시" value="{query}" placeholder="문서 검색" readonly><span>{result}</span><button type="button" class="icon-button"{disabled} aria-label="이전 결과">{icon("up")}</button><button type="button" class="icon-button"{disabled} aria-label="다음 결과">{icon("down")}</button></div>'
        return bar + ('<p>일치하는 내용을 찾지 못했어요.</p>' if empty is True else '')

    renders = {
        'colors': {'light': swatches, 'dark': swatches},
        'typography': {name: f'<p class="type-spec">{e(tokens["fontRoles"][role["family"]])} · {tokens["fontSizes"][role["size"]]}px · {role["weight"]} · 행간 {round(tokens["fontSizes"][role["size"]] * tokens["lineHeights"][role["leading"]], 2)}px</p><p class="type-{e(name)}">{e(sample["body"] if name in ["body","bodySmall"] else "깊이 읽는 시간 · Markdown 0123456789" if name != "code" else "fun dive(depth: Int) / 0 O 1 l I")}</p>' for name, role in tokens['typography'].items()},
        'buttons': {
            'normal': button('파일 열기',leading='plus'),
            'secondary': button('다시 선택', 'secondary'),
            'quiet': button('목록에서 제거', 'quiet'),
            'pressed': button('파일 열기 · 누름', 'pressed', 'plus'),
            'disabled': button('파일 열기 · 비활성', disabled=True),
            'loading': button('준비 중', 'loading',disabled=True),
        },
        'layout': {
            'spacing': ''.join(f'<div class="spacing-example"><code>{e(key)}</code><span style="display:inline-block;background:var(--primary);width:{value}px;height:8px"></span><small>{value}</small></div>' for key, value in tokens['spacing'].items()),
            'radius': ''.join(f'<div class="radius-example" style="border-radius:{value}px"><code>{e(key)}</code><small>{value}</small></div>' for key, value in tokens['radii'].items()),
        },
        'documents': {
            'normal': document_rows(sample['favorites']),
            'empty': '<div class="panel"><strong>아직 문서가 없어요</strong><p>첫 문서를 열어보세요.</p></div>',
            'error': '<div class="panel"><strong class="error">문서를 열지 못했어요</strong><p>접근 권한을 확인하거나 파일을 다시 선택해주세요.</p></div>',
        },
        'topbar': {state: topbar(state) for state in ['default','back','actions','longTitle']},
        'search': {'idle': search_bar('idle'), 'results': search_bar(False), 'empty': search_bar(True)},
        'content': {'code': f'<pre>{e(sample["code"])}</pre>', 'table': table},
        'icons': {'brand': '<p>MDive · 대표 심볼</p><div class="brand-original" data-palette="deepsea" data-theme="dark">' + brand_svg + '</div><p>대표 심볼은 앱 정체성에, 동작 아이콘은 조작에 사용합니다.</p>', 'normal': '<div class="icon-grid">' + ''.join(f'<div>{icon(key)}<small>{e(key)}</small></div>' for key in icons['paths']) + '</div>'},
        'navigation': {'normal': '<div class="tabs"><span class="selected">목차</span><span>책갈피</span></div><p class="muted">한 패널의 두 탭 · 배치 초안</p>'},
        'feedback': {
            'loading': '<div class="notice"><span class="loading-dot"></span><div><strong>문서를 준비하고 있어요</strong><p>로딩 표현 초안</p></div></div>',
            'empty': f'<div class="notice">{icon("bookmark")}<div><strong>아직 책갈피가 없어요</strong><p>다시 읽고 싶은 위치를 저장해보세요.</p></div></div>',
            'error': f'<div class="notice error">{icon("file")}<div><strong>문서를 열지 못했어요</strong><p>다시 선택하거나 목록에서 제거할 수 있어요.</p>{button("다시 선택", "secondary")}</div></div>',
        },
    }
    if not set(ids).issubset(renders):
        raise ValueError('Register each catalog ID in both platform renderers')
    for entry in entries:
        if entry['category'] not in ['foundations', 'components']:
            raise ValueError(f'Unknown catalog category: {entry["category"]}')
        if entry['id'] == 'buttons' and (not entry['variants'] or len(entry['variants']) != len(set(entry['variants'])) or not set(entry['variants']).issubset({'primary', 'secondary', 'quiet'})):
            raise ValueError('Register each button variant in both platform renderers')
        if not entry['states'] or len(entry['states']) != len(set(entry['states'])):
            raise ValueError(f'Empty or duplicate states: {entry["id"]}')
        if not set(entry['states']).issubset(renders[entry['id']]):
            raise ValueError(f'Register each state in both platform renderers: {entry["id"]}')
    columns = ''
    for theme_id, theme in themes.items():
        for mode in ['light', 'dark']:
            sections = ''
            for entry in entries:
                if entry['id'] == 'buttons':
                    states = ''
                    for variant in entry['variants']:
                        states += f'<h4>{e(variant)}</h4><div class="state-matrix">'
                        for state in entry['states']:
                            classes = ('secondary' if variant == 'secondary' else 'quiet' if variant == 'quiet' else '') + (' ' + state if state in ['pressed', 'loading'] else '')
                            states += f'<div class="example" data-state="{e(state)}"><p><small>{e(state)}</small></p>{button("파일 열기",classes,"plus",state in ["disabled","loading"])}</div>'
                        states += '</div>'
                else:
                    states = ''.join(f'<div class="example" data-state="{e(state)}"><p><small>{e(state)} · 초안</small></p>{renders[entry["id"]][state]}</div>' for state in entry['states'] if entry['id'] != 'colors' or state == mode)
                anatomy = ' · '.join(map(e, entry['anatomy']))
                rules = ''.join(f'<div class="guide"><h3>{title}</h3><ul>' + ''.join(f'<li>{e(item)}</li>' for item in entry[key]) + '</ul></div>' for key, title in [('behavior','동작과 상태'),('usage','사용 기준'),('accessibility','접근성')])
                sections += f'<section data-entry="{e(entry["id"])}" id="{e(theme_id)}-{mode}-{e(entry["id"])}"><p class="eyebrow">{e(entry["category"])} / 초안</p><h2>{e(entry["title"])}</h2><p class="purpose">{e(entry["purpose"])}</p><div class="guide"><h3>구성</h3><p>{anatomy}</p></div><h3>변형과 상태</h3>{states}{rules}</section>'
            columns += f'<div class="theme" data-palette="{e(theme_id)}" data-theme="{mode}"><h2>{e(theme["name"])} · {mode.title()}</h2>{sections}</div>'
    nav = ''
    for category, label in [('foundations', '기초 규칙'), ('components', '컴포넌트')]:
        nav += f'<h2>{label}</h2>' + ''.join(f'<a data-entry="{e(entry["id"])}" href="#deepsea-light-{e(entry["id"])}">{e(entry["title"])}</a>' for entry in entries if entry['category'] == category)
    options = ''.join(f'<option value="{e(key)}">{e(theme["name"])}</option>' for key, theme in themes.items())
    script = '''<script>
const palette = document.querySelector('#palette'), mode = document.querySelector('#mode');
let entry = 'buttons';
function update() {
  document.querySelectorAll('.theme').forEach(theme => {
    theme.hidden = theme.dataset.palette !== palette.value || theme.dataset.theme !== mode.value;
    theme.querySelectorAll('section').forEach(section => section.hidden = section.dataset.entry !== entry);
  });
  document.querySelectorAll('nav a[data-entry]').forEach(link => {
    link.href = '#' + palette.value + '-' + mode.value + '-' + link.dataset.entry;
    if (link.dataset.entry === entry) link.setAttribute('aria-current', 'page'); else link.removeAttribute('aria-current');
  });
}
document.querySelectorAll('nav a[data-entry]').forEach(link => link.addEventListener('click', () => { entry = link.dataset.entry; update(); }));
palette.addEventListener('change', update); mode.addEventListener('change', update); update();
</script>'''
    page = '<!doctype html>\n<html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>MDive 디자인 시스템</title><link rel="stylesheet" href="tokens.css"><link rel="stylesheet" href="../catalog.css"><main><header class="site-head"><div><p class="eyebrow">MDIVE / DESIGN SYSTEM</p><h1>디자인 시스템</h1><p>컴포넌트 검토용 초안 · 화면 적용 전의 독립 예시입니다.</p></div><div class="review-controls"><label>색상안 <select id="palette">' + options + '</select></label><label>밝기 <select id="mode"><option value="light">라이트</option><option value="dark">다크</option></select></label></div></header><div class="doc-shell"><nav aria-label="디자인 시스템 목차">' + nav + '<hr><a href="../../docs/product/design-system.md">관리 설명</a><a href="../../docs/product/design-system-references.md">공식 사례 조사</a></nav><div class="themes">' + columns + '</div></div><footer>사용 규칙과 상태는 공통 원본에서 생성합니다. HTML 예시는 정적이며 실제 입력·포커스·동작 검증은 Compose 카탈로그에서 진행합니다.</footer></main>' + script + '</html>\n'
    return {GENERATED / 'DesignTokens.kt': kotlin, GENERATED / 'CatalogEntries.kt': manifest, GENERATED / 'CatalogSamples.kt': samples, GENERATED / 'CatalogIcons.kt': icon_kotlin, ROOT / 'design-system/generated/tokens.css': css, ROOT / 'design-system/generated/catalog.html': page}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        parser.exit(1, 'Stale generated outputs:\n' + '\n'.join(stale) + '\nRun python3 tools/generate_design_system.py\n')
    print('Design system outputs are current.' if args.check else 'Generated design system outputs.')


if __name__ == '__main__':
    main()
