"""Trace the approved raster mechanically; generate the Android vector from the shared SVG.

Normal generation/check uses only stdlib. --trace requires Pillow and potrace 1.16.
"""
import argparse
import re
import subprocess
import tempfile
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SVG = ROOT / 'design-system/illustrations/document-plunge.svg'
PNG = ROOT / 'design-system/illustrations/source/document-plunge-approved.png'
VECTOR = ROOT / 'designsystem/src/main/res/drawable/mdive_document_plunge.xml'
NS = '{http://www.w3.org/2000/svg}'


def trace():
    from PIL import Image
    image = Image.open(PNG).convert('RGB').convert('L')
    mask = image.point(lambda value: 255 if value < 128 else 0)
    bounds = mask.getbbox()
    if bounds is None:
        raise ValueError('Approved source has no foreground')
    width, height = bounds[2] - bounds[0], bounds[3] - bounds[1]
    with tempfile.TemporaryDirectory() as temp:
        bitmap, output = Path(temp) / 'source.pbm', Path(temp) / 'trace.svg'
        mask.crop(bounds).point(lambda value: 0 if value else 255).convert('1').save(bitmap)
        subprocess.run(['potrace', str(bitmap), '--svg', '--flat', '--turdsize', '4', '--opttolerance', '0.2', '--output', str(output)], check=True)
        tree = ET.parse(output).getroot()
    group = tree.find(NS + 'g')
    paths = '\n'.join('    <path d="' + ' '.join(path.attrib['d'].split()) + '"/>' for path in group.findall(NS + 'path'))
    SVG.write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" fill="currentColor">
  <!-- Mechanically traced from source/document-plunge-approved.png with potrace 1.16. -->
  <g transform="{group.attrib['transform']}">
{paths}
  </g>
</svg>
''')


def android_vector():
    tree = ET.parse(SVG).getroot()
    _, _, width, height = tree.attrib['viewBox'].split()
    group = tree.find(NS + 'g')
    values = re.fullmatch(r'translate\(([-\d.]+),([-\d.]+)\) scale\(([-\d.]+),([-\d.]+)\)', group.attrib['transform'])
    if values is None:
        raise ValueError('Unsupported trace transform')
    x, y, sx, sy = values.groups()
    paths = '\n'.join(f'    <path android:fillColor="#FFFFFFFF" android:fillType="nonZero" android:pathData="{path.attrib["d"]}" />' for path in group.findall(NS + 'path'))
    display_height = 160 * float(height) / float(width)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_welcome_illustration.py. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="160dp" android:height="{display_height:.6f}dp" android:viewportWidth="{width}" android:viewportHeight="{height}">
  <group android:translateX="{x}" android:translateY="{y}" android:scaleX="{sx}" android:scaleY="{sy}">
{paths}
  </group>
</vector>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--trace', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.trace:
        if args.check:
            parser.error('--trace and --check are mutually exclusive')
        trace()
    output = android_vector()
    if args.check:
        if not VECTOR.exists() or VECTOR.read_text() != output:
            raise SystemExit('Welcome illustration vector is stale')
        print('Welcome illustration vector is current.')
    else:
        VECTOR.write_text(output)
        print('Generated welcome illustration vector.')


if __name__ == '__main__':
    main()
